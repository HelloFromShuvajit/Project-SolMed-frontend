/**
 * Writes config/api.js from SOLMED_API_URL (Vercel / local .env).
 * Default for local development: http://localhost:8081
 */
const fs = require('fs');
const path = require('path');

function loadEnvFile(fileName) {
    const filePath = path.join(__dirname, '..', fileName);
    if (!fs.existsSync(filePath)) return;
    for (const line of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const match = trimmed.match(/^SOLMED_API_URL\s*=\s*(.*)$/);
        if (match && !process.env.SOLMED_API_URL) {
            process.env.SOLMED_API_URL = match[1].trim().replace(/^["']|["']$/g, '');
        }
    }
}

loadEnvFile('.env');
loadEnvFile('.env.local');

const DEFAULT_LOCAL = 'http://localhost:8081';
const raw = (process.env.SOLMED_API_URL || DEFAULT_LOCAL).trim().replace(/\/$/, '');
const outPath = path.join(__dirname, '..', 'config', 'api.js');

const contents = `/** Generated by scripts/generate-api-config.js - do not edit by hand for deploys. */
window.SOLMED_API_BASE = ${JSON.stringify(raw)};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, contents, 'utf8');
console.log('Wrote', outPath, '->', raw);
